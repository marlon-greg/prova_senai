// ---------- consultas ----------
const norm = s => String(s || "").normalize("NFD").replace(/[̀-ͯ]/g, "").toLowerCase().replace(/\s+/g, " ").trim();
export const unidadePorId = id => PLANO_CURSO.unidades.find(u => u.id === id) || null;
// matéria em texto livre (da prova/turma) -> unidade curricular do plano (ou null)
export function unidadeDaMateria(materia) {
  const m = norm(materia);
  if (!m) return null;
  return PLANO_CURSO.unidades.find(u => norm(u.nome) === m)
    || PLANO_CURSO.unidades.find(u => u.chaves.some(c => c[0] === "=" ? m === c.slice(1) : m.includes(c)))
    || (m.length >= 4 && PLANO_CURSO.unidades.find(u => norm(u.nome).includes(m))) || null;
}
// unidades de um semestre do curso (1 a 4); sem semestre = todas
export const unidadesDoSemestre = s => PLANO_CURSO.unidades.filter(u => !s || u.semestres[s]);
export const rotuloTec = u => u?.tipoTec === "basicas" ? "Capacidades básicas" : "Capacidades técnicas";
// nível de um conhecimento: "bd.k2.4.1" -> 3
export const nivelK = id => id.split(".k")[1].split(".").length;
const paiK = id => id.slice(0, id.lastIndexOf(".")).includes(".k") && nivelK(id) > 1 ? id.slice(0, id.lastIndexOf(".")) : null;
const descende = (id, de) => id === de || id.startsWith(de + ".");

// Tópicos que a prova cobre. prova.planoCurso = { unidade: "bd", itens: [ids] }:
// unidade vazia = a da matéria; itens vazio = a unidade inteira. Conhecimento marcado inclui os subitens.
export function topicosDaProva(p) {
  const pc = p?.planoCurso || {};
  if (pc.unidade === "nenhuma") return null;   // o professor escolheu não mostrar
  const u = unidadePorId(pc.unidade) || unidadeDaMateria(p?.materia);
  if (!u) return null;
  const itens = Array.isArray(pc.itens) ? pc.itens.filter(i => i.startsWith(u.id + ".")) : [];
  const tudo = !itens.length, tem = new Set(itens);
  const kMarc = itens.filter(i => i.includes(".k"));
  const conInc = u.con.filter(([id]) => tudo || kMarc.some(k => descende(id, k)));
  // ancestrais aparecem como contexto (cabeçalho) mesmo sem estarem marcados
  const ids = new Set(conInc.map(([id]) => id));
  for (const id of [...ids]) { let p2 = paiK(id); while (p2) { ids.add(p2); p2 = paiK(p2); } }
  return {
    unidade: u, inteira: tudo,
    tec: u.tec.filter(([id]) => tudo || tem.has(id)),
    soc: u.soc.filter(([id]) => tudo || tem.has(id)),
    con: u.con.filter(([id]) => ids.has(id))
  };
}

// HTML (lista aninhada) dos conhecimentos: nível 1 com os de nível 2 embaixo; nível 3+ vai em linha
export function htmlConhecimentos(con, esc) {
  const filhos = id => con.filter(([c]) => paiK(c) === id);
  const linha3 = id => { const f = filhos(id); return f.length ? `: <span class="pc-sub">${f.map(([c, t]) => esc(t) + (filhos(c).length ? ` (${filhos(c).map(([, t2]) => esc(t2)).join(", ")})` : "")).join(", ")}</span>` : ""; };
  return `<ol class="pc-con">${con.filter(([c]) => nivelK(c) === 1).map(([c, t]) => {
    const f = filhos(c);
    return `<li><b>${esc(t)}</b>${f.length ? `<ul>${f.map(([c2, t2]) => `<li>${esc(t2)}${linha3(c2)}</li>`).join("")}</ul>` : ""}</li>`;
  }).join("")}</ol>`;
}
